from data.normalize import normalize_amharic
import json, sys
from common import config as cfg  # must load before transformers/datasets
import evaluate

CHAR_MAP = {
    "ሐ": "ሀ", "ሑ": "ሁ", "ሒ": "ሂ", "ሓ": "ሃ", "ሔ": "ሄ", "ሕ": "ህ", "ሖ": "ሆ",
    "ኀ": "ሀ", "ኁ": "ሁ", "ኂ": "ሂ", "ኃ": "ሃ", "ኄ": "ሄ", "ኅ": "ህ", "ኆ": "ሆ",
    "ዐ": "አ", "ዑ": "ኡ", "ዒ": "ኢ", "ዓ": "ኣ", "ዔ": "ኤ", "ዕ": "እ", "ዖ": "ኦ",
    "ሠ": "ሰ", "ሡ": "ሱ", "ሢ": "ሲ", "ሣ": "ሳ", "ሤ": "ሴ", "ሥ": "ስ", "ሦ": "ሶ",
    "ፀ": "ጸ", "ፁ": "ጹ", "ፂ": "ጺ", "ፃ": "ጻ", "ፄ": "ጼ", "ፅ": "ጽ", "ፆ": "ጾ",
}
PUNCT = '!"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~።፣፤፥፦'

def normalize_amharic(text):
    for src, tgt in CHAR_MAP.items():
        text = text.replace(src, tgt)
    for p in PUNCT:
        text = text.replace(p, " ")
    return " ".join(text.split()).strip()

rows = [json.loads(l) for l in open(sys.argv[1], encoding="utf-8")]
pred = [normalize_amharic(r["hypothesis"]) for r in rows]
ref = [normalize_amharic(r["reference"]) for r in rows]
wer = evaluate.load("wer").compute(predictions=pred, references=ref) * 100
cer = evaluate.load("cer").compute(predictions=pred, references=ref) * 100
print(f"{sys.argv[1]}: n={len(rows)}  WER={wer:.2f}  CER={cer:.2f}")